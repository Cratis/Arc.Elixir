defmodule Arc.ProxyGenerator do
  @moduledoc """
  Generates TypeScript proxies for the React frontend packages (`@cratis/arc`, `@cratis/arc.react`)
  from the commands and read models of an `Arc.Application`.

  Proxy generation is **opt-in**. Nothing is generated unless you run `mix arc.gen.proxies` or
  configure the `:arc` compiler. A backend serving LiveView or an API to another client never
  generates TypeScript.

      # mix.exs
      def project do
        [
          # ...
          compilers: Mix.compilers() ++ [:arc],
          arc: [application: MyApp.Arc, output: "assets/src/arc"]
        ]
      end

  ## What is generated

  One file per artifact, in a folder that mirrors the module namespace after the leading
  `segments_to_skip` segments:

    * a command module becomes a `Command` class with its interface, route, roles, property
      descriptors, client-side validator and a `use` hook
    * each query of a read model becomes a `QueryFor` (or `ObservableQueryFor`) class with
      parameters, sorting helpers and the `use`, `useWithPaging`, `useSuspense` and `when` hooks
    * each model and nested schema becomes a class with `@field` decorators
    * an `index.ts` per folder re-exports the generated files

  The output follows the C# proxy generator's templates, so the frontend packages consume it
  unchanged.

  ## Safety

  Every generated file starts with `// @generated by Cratis. Source: <module>. Hash: <sha256>`.
  A file without that marker is never overwritten, and stale cleanup deletes only files that
  carry it. Output is deterministic: generating twice produces identical bytes, and an unchanged
  file is not rewritten.

  ## Options

  Read from `arc:` in `mix.exs`, or `config :my_app, MyApp.Arc, proxies: [...]`, or flags to the
  task.

    * `:application` - the `Arc.Application` module (required)
    * `:output` - the directory to generate into (required)
    * `:remove_stale` - delete generated files for artifacts that no longer exist; default `true`
  """

  alias Arc.{Descriptor, Naming}
  alias Arc.ProxyGenerator.{Render, TypeScript}

  @marker "// @generated by Cratis"
  @segment ~r/\A[A-Za-z0-9_$-]+\z/

  defmodule Artifact do
    @moduledoc false
    defstruct [:path, :source, :body]
  end

  @type result :: %{written: [String.t()], unchanged: [String.t()], removed: [String.t()]}

  @doc """
  Renders every proxy without touching the file system. Returns files with a path relative to the output
  directory, the source module, and the TypeScript body.
  """
  @spec render(module()) :: [Artifact.t()]
  def render(application) do
    state = Arc.Application.state(application)
    config = state.config

    opts = %{
      segments_to_skip: config[:segments_to_skip],
      route_prefix: config[:route_prefix]
    }

    commands =
      for d <- state.commands do
        %Artifact{
          path: path(d.module, d.name, opts),
          source: inspect(d.module),
          body: Render.command(d, opts)
        }
      end

    queries =
      for d <- state.read_models, q <- d.queries do
        name = Naming.pascal(q.name)

        %Artifact{
          path: path(d.module, name, opts),
          source: "#{inspect(d.module)}.#{name}",
          body: Render.query(d, q, opts)
        }
      end

    types = type_files(state, opts)
    files = commands ++ queries ++ types
    ensure_no_collisions!(files)
    Enum.sort_by(files, & &1.path)
  end

  defp type_files(state, opts) do
    command_types =
      Enum.flat_map(state.commands, fn d ->
        Enum.map(d.fields, & &1.type) ++ List.wrap(d.response)
      end)

    query_types =
      for d <- state.read_models,
          q <- d.queries,
          t <- [d.model | Enum.map(q.params, & &1.type)],
          do: t

    overrides = Map.new(state.read_models, fn d -> {d.model, d.model_types} end)

    (command_types ++ query_types)
    |> TypeScript.reachable_types()
    |> Enum.map(fn module ->
      {_ns, name} = Naming.module_parts(module)
      fields = TypeScript.model_fields(module, Map.get(overrides, module))

      %Artifact{
        path: path(module, name, opts),
        source: inspect(module),
        body: Render.type(module, fields, opts)
      }
    end)
  end

  defp path(module, name, opts) do
    folder = TypeScript.folder(module, opts.segments_to_skip)
    relative = if folder == "", do: "#{name}.ts", else: "#{folder}/#{name}.ts"
    validate_path!(relative, module)
    relative
  end

  defp validate_path!(relative, module) do
    relative
    |> String.replace_suffix(".ts", "")
    |> String.split("/")
    |> Enum.each(fn segment ->
      unless Regex.match?(@segment, segment) do
        raise ArgumentError,
              "#{inspect(module)} would generate the unsafe path segment #{inspect(segment)}"
      end
    end)
  end

  defp ensure_no_collisions!(files) do
    files
    |> Enum.group_by(& &1.path)
    |> Enum.each(fn
      {_path, [_]} ->
        :ok

      {path, many} ->
        raise ArgumentError,
              "Proxy name collision: #{inspect(Enum.map(many, & &1.source))} all generate #{path}. Rename one, or move it to another namespace."
    end)
  end

  @doc """
  Generates proxies into `output`.

  ## Options

    * `:output` - the directory (required)
    * `:remove_stale` - default `true`
    * `:dry_run` - report what would change without writing
  """
  @spec generate(module(), keyword()) :: {:ok, result()} | {:error, [String.t()]}
  def generate(application, opts) do
    output = Keyword.fetch!(opts, :output)
    dry_run? = Keyword.get(opts, :dry_run, false)
    files = render(application)
    expected = MapSet.new(files, & &1.path)

    with {:ok, plan} <- plan(files, output) do
      indexes = index_plan(files, output)
      all = plan ++ indexes

      stale =
        if Keyword.get(opts, :remove_stale, true),
          do: stale_files(output, expected, indexes),
          else: []

      unless dry_run? do
        Enum.each(all, fn
          {:write, path, content} ->
            File.mkdir_p!(Path.dirname(path))
            File.write!(path, content)

          {:keep, _} ->
            :ok
        end)

        Enum.each(stale, &File.rm!/1)
        unless stale == [], do: prune_empty_directories(output)
      end

      {:ok,
       %{
         written: for({:write, path, _} <- all, do: Path.relative_to(path, output)),
         unchanged: for({:keep, path} <- all, do: Path.relative_to(path, output)),
         removed: Enum.map(stale, &Path.relative_to(&1, output))
       }}
    end
  end

  # Planning

  defp plan(files, output) do
    results =
      Enum.map(files, fn file ->
        target = Path.join(output, file.path)
        content = marked(file.source, file.body)

        case existing(target) do
          :missing ->
            {:ok, {:write, target, content}}

          {:generated, ^content} ->
            {:ok, {:keep, target}}

          {:generated, _other} ->
            {:ok, {:write, target, content}}

          :hand_written ->
            {:error,
             "Refusing to overwrite hand-written file #{target}: it has no '#{@marker}' marker."}
        end
      end)

    case Enum.filter(results, &match?({:error, _}, &1)) do
      [] -> {:ok, Enum.map(results, fn {:ok, step} -> step end)}
      errors -> {:error, Enum.map(errors, &elem(&1, 1))}
    end
  end

  defp existing(path) do
    case File.read(path) do
      {:error, :enoent} ->
        :missing

      {:ok, content} ->
        if String.starts_with?(content, @marker), do: {:generated, content}, else: :hand_written
    end
  end

  defp marked(source, body) do
    hash = :crypto.hash(:sha256, body) |> Base.encode16()
    "#{@marker}. Source: #{source}. Hash: #{hash}\n" <> body
  end

  # index.ts files

  defp index_plan(files, output) do
    files
    |> Enum.group_by(&Path.dirname(&1.path))
    |> Enum.map(fn {dir, in_dir} ->
      target = Path.join([output, dir, "index.ts"])

      names =
        in_dir |> Enum.map(&Path.basename(&1.path, ".ts")) |> Enum.sort_by(&String.downcase/1)

      exports = Enum.map(names, &"export * from './#{&1}';")

      case existing(target) do
        :hand_written ->
          merged = merge_index(File.read!(target), exports)
          if merged == File.read!(target), do: {:keep, target}, else: {:write, target, merged}

        _ ->
          body = Enum.join(exports, "\n") <> "\n"
          content = marked("index", body)

          case existing(target) do
            {:generated, ^content} -> {:keep, target}
            _ -> {:write, target, content}
          end
      end
    end)
    |> Enum.sort_by(fn
      {_, path, _} -> path
      {_, path} -> path
    end)
  end

  defp merge_index(existing, exports) do
    present = existing |> String.split("\n") |> MapSet.new(&String.trim/1)
    missing = Enum.reject(exports, &MapSet.member?(present, &1))

    if missing == [],
      do: existing,
      else: String.trim_trailing(existing) <> "\n" <> Enum.join(missing, "\n") <> "\n"
  end

  # Stale files

  defp stale_files(output, expected, indexes) do
    kept_indexes =
      MapSet.new(indexes, fn
        {_, path, _} -> path
        {_, path} -> path
      end)

    output
    |> Path.join("**/*.ts")
    |> Path.wildcard()
    |> Enum.filter(fn path ->
      relative = Path.relative_to(path, output)

      generated?(path) and
        if Path.basename(path) == "index.ts",
          do: not MapSet.member?(kept_indexes, path),
          else: not MapSet.member?(expected, relative)
    end)
  end

  defp generated?(path) do
    case File.read(path) do
      {:ok, content} -> String.starts_with?(content, @marker)
      _ -> false
    end
  end

  defp prune_empty_directories(output) do
    output
    |> Path.join("**/")
    |> Path.wildcard()
    |> Enum.sort_by(&String.length/1, :desc)
    |> Enum.each(fn dir ->
      if dir != output and File.dir?(dir) and File.ls!(dir) == [], do: File.rmdir(dir)
    end)
  end

  @doc """
  Resolves generation options for `application`: `arc:` in `mix.exs`, then the application's
  `:proxies` configuration, then `overrides`. Returns `nil` when no output directory is configured,
  which is how proxy generation stays opt-in.
  """
  @spec options(module(), keyword()) :: keyword() | nil
  def options(application, overrides \\ []) do
    configured = application.config() |> Keyword.get(:proxies, [])
    opts = Keyword.merge(configured, overrides)
    if opts[:output], do: opts, else: nil
  end

  @doc false
  @spec descriptor_name(Descriptor.t()) :: String.t()
  def descriptor_name(%Descriptor{name: name}), do: name
end
