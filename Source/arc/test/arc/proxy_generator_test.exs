defmodule Arc.ProxyGeneratorTest do
  use ExUnit.Case, async: true

  alias Arc.ProxyGenerator

  @moduletag :tmp_dir

  defp generate(tmp_dir, opts \\ []) do
    {:ok, result} =
      ProxyGenerator.generate(ArcFixtures.App, Keyword.merge([output: tmp_dir], opts))

    result
  end

  defp read(tmp_dir, relative), do: File.read!(Path.join(tmp_dir, relative))

  test "generates a file per command, query and type, plus an index per folder", %{tmp_dir: dir} do
    result = generate(dir)

    assert "Authors/Registration/RegisterAuthor.ts" in result.written
    assert "Authors/Listing/AllAuthors.ts" in result.written
    assert "Authors/Listing/LiveAuthors.ts" in result.written
    assert "Authors/Author.ts" in result.written
    assert "Authors/Listing/index.ts" in result.written
  end

  test "every file starts with the generated marker, source and hash", %{tmp_dir: dir} do
    generate(dir)

    [first | _] = read(dir, "Authors/Registration/RegisterAuthor.ts") |> String.split("\n")

    assert first =~
             ~r/\A\/\/ @generated by Cratis\. Source: ArcFixtures\.Authors\.Registration\.RegisterAuthor\. Hash: [0-9A-F]{64}\z/
  end

  test "a command carries its route, roles, response, rules and slice location", %{tmp_dir: dir} do
    generate(dir)

    rename = read(dir, "Authors/Registration/RenameAuthor.ts")

    assert rename =~
             "export class RenameAuthor extends Command<IRenameAuthor, string> implements IRenameAuthor"

    assert rename =~ "readonly route: string = '/api/authors/registration/rename-author';"
    assert rename =~ "readonly roles: string[] = ['admin'];"
    assert rename =~ "new ArcSliceLocation('', 'Authors', 'Registration')"
    assert rename =~ "super(String, false);"

    register = read(dir, "Authors/Registration/RegisterAuthor.ts")
    assert register =~ "this.ruleFor(c => c.name).notEmpty();"
    assert register =~ "this.ruleFor(c => c.name).maxLength(10);"
    assert register =~ "this.ruleFor(c => c.age).greaterThanOrEqual(0);"
    assert register =~ "new PropertyDescriptor('id', Guid, false),"
    assert register =~ "import { Guid } from '@cratis/fundamentals';"
  end

  test "a query carries its fully qualified name, parameters and hooks", %{tmp_dir: dir} do
    generate(dir)

    by_id = read(dir, "Authors/Listing/ById.ts")
    assert by_id =~ "readonly queryName: string = 'ArcFixtures.Authors.Listing.Authors.ById';"
    assert by_id =~ "export interface ByIdParameters {\n    id: Guid;\n}"

    assert by_id =~
             "get requiredRequestParameters(): string[] {\n        return [\n            'id',"

    assert by_id =~ "import { Author } from '../Author';"

    live = read(dir, "Authors/Listing/LiveAuthors.ts")
    assert live =~ "export class LiveAuthors extends ObservableQueryFor<Author[]>"
    assert live =~ "static useChangeStream("
  end

  test "a model is generated as a decorated class", %{tmp_dir: dir} do
    generate(dir)

    assert read(dir, "Authors/Author.ts") =~
             "export class Author {\n    @field(String)\n    id!: string;"
  end

  test "output is deterministic and an unchanged file is not rewritten", %{tmp_dir: dir} do
    first = generate(dir)
    before = read(dir, "Authors/Registration/RegisterAuthor.ts")
    second = generate(dir)

    assert first.written != []
    assert second.written == []
    assert length(second.unchanged) == length(first.written)
    assert read(dir, "Authors/Registration/RegisterAuthor.ts") == before
  end

  test "a hand-written file is never overwritten", %{tmp_dir: dir} do
    File.mkdir_p!(Path.join(dir, "Authors/Registration"))

    File.write!(
      Path.join(dir, "Authors/Registration/RegisterAuthor.ts"),
      "export const mine = 1;\n"
    )

    assert {:error, [message]} = ProxyGenerator.generate(ArcFixtures.App, output: dir)
    assert message =~ "Refusing to overwrite hand-written file"

    assert File.read!(Path.join(dir, "Authors/Registration/RegisterAuthor.ts")) ==
             "export const mine = 1;\n"
  end

  test "stale generated files are removed and hand-written files survive", %{tmp_dir: dir} do
    generate(dir)
    stale = Path.join(dir, "Gone/Old.ts")
    File.mkdir_p!(Path.dirname(stale))
    File.write!(stale, "// @generated by Cratis. Source: Old. Hash: X\nexport {};\n")
    File.write!(Path.join(dir, "Notes.ts"), "export const note = 1;\n")

    result = generate(dir)

    assert "Gone/Old.ts" in result.removed
    refute File.exists?(stale)
    refute File.exists?(Path.join(dir, "Gone"))
    assert File.exists?(Path.join(dir, "Notes.ts"))
  end

  test "--check style dry runs write nothing", %{tmp_dir: dir} do
    result = generate(dir, dry_run: true)

    assert result.written != []
    assert File.ls!(dir) == []
  end

  test "a hand-written index.ts is merged, never replaced", %{tmp_dir: dir} do
    File.mkdir_p!(Path.join(dir, "Authors/Listing"))
    File.write!(Path.join(dir, "Authors/Listing/index.ts"), "export * from './Mine';\n")

    generate(dir)

    index = read(dir, "Authors/Listing/index.ts")
    assert index =~ "export * from './Mine';"
    assert index =~ "export * from './AllAuthors';"
    refute index =~ "@generated"
  end

  test "two artifacts that generate the same file are a name collision" do
    defmodule Collide.One do
      use Arc.ReadModel, model: ArcFixtures.Authors.Author
      @query many: true
      def same(_a, _c), do: {:ok, []}
    end

    defmodule Collide.Two do
      use Arc.ReadModel, model: ArcFixtures.Authors.Author
      @query many: true
      def same(_a, _c), do: {:ok, []}
    end

    defmodule CollideApp do
      use Arc.Application,
        otp_app: :cratis_arc,
        artifacts: [Collide.One, Collide.Two],
        segments_to_skip: 0
    end

    # Both live in the same namespace, so route and file collide.
    assert_raise ArgumentError, ~r/Duplicate Arc query route/, fn ->
      Arc.Application.refresh(CollideApp)
    end
  end
end
